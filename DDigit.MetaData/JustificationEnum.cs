namespace DDigit.MetaData;


/// <summary>
/// Indicates how text is aligned in a text field
/// </summary>
public enum JustificationEnum : short
{
  /// <summary>
  /// No justification
  /// </summary>
  None = 0,

  /// <summary>
  /// Text is left justiefied
  /// </summary>
  Left = 1,

  /// <summary>
  /// Text is centered
  /// </summary>
  Center = 2,

  /// <summary>
  /// Text is right justified
  /// </summary>
  Right = 3
}
